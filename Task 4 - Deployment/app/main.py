if DASHBOARD_DIR.exists():
    app.mount("/static", StaticFiles(directory=DASHBOARD_DIR), name="static")

    @app.get("/", tags=["meta"])
    def dashboard():
        return FileResponse(DASHBOARD_DIR / "index.html")
